import {generateKeyPairSync,createHash} from 'node:crypto';
import {existsSync,mkdirSync,readFileSync,renameSync,rmSync,writeFileSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {spawnSync} from 'node:child_process';

const repository=process.env.MYR5_GITHUB_REPOSITORY||'MomInc-MBS/coach-app';
const activeSecret='PACK_CATALOG_SIGNING_PRIVATE_JWK';
const output=new URL('../packs/catalog-keys.generated.mjs',import.meta.url);
const current=readFileSync(output,'utf8');
if(!current.includes('PUBLIC_PACK_CATALOG_KEYS=Object.freeze([])'))throw Error('Catalog keys are already provisioned. Use the documented dual-key rotation procedure instead of replacing them.');

function keyPair(){
 return generateKeyPairSync('ed25519',{publicKeyEncoding:{format:'jwk'},privateKeyEncoding:{format:'jwk'}});
}
function fingerprint(key){return createHash('sha256').update(Buffer.from(key.x,'base64url')).digest('hex');}
function run(command,args,options={}){
 const result=spawnSync(command,args,{encoding:'utf8',windowsHide:true,...options});
 if(result.status!==0)throw Error((result.stderr||result.stdout||command+' failed').trim());
 return result;
}

const active=keyPair(),recovery=keyPair();
const activeFingerprint=fingerprint(active.publicKey),recoveryFingerprint=fingerprint(recovery.publicKey);
const stamp=new Date().toISOString().slice(0,10);
const activeId=`myr5-pack-release-${stamp}-${activeFingerprint.slice(0,12)}`;
const recoveryId=`myr5-pack-recovery-${stamp}-${recoveryFingerprint.slice(0,12)}`;

run('gh',['secret','set',activeSecret,'--repo',repository],{
 input:JSON.stringify(active.privateKey),
 env:{...process.env,GH_PROMPT_DISABLED:'1'}
});

const recoveryRoot=join(process.env.LOCALAPPDATA||dirname(process.env.USERPROFILE||process.cwd()),'MYR5','catalog-keys');
const recoveryPath=join(recoveryRoot,`${recoveryId}.jwk.dpapi`);
if(existsSync(recoveryPath))throw Error('The recovery-key destination already exists.');
mkdirSync(recoveryRoot,{recursive:true});
const powershell=join(process.env.SystemRoot||'C:\\Windows','System32','WindowsPowerShell','v1.0','powershell.exe');
const protect=[
 '$destination=$env:MYR5_RECOVERY_PATH',
 '$plaintext=[Console]::In.ReadToEnd()',
 "Add-Type -AssemblyName 'System.Security'",
 '$bytes=[Text.Encoding]::UTF8.GetBytes($plaintext)',
 "$entropy=[Text.Encoding]::UTF8.GetBytes('MYR5 pack catalog recovery v1')",
 '$cipher=[Security.Cryptography.ProtectedData]::Protect($bytes,$entropy,[Security.Cryptography.DataProtectionScope]::CurrentUser)',
 '[IO.File]::WriteAllBytes($destination,$cipher)'
].join(';');
try{
 run(powershell,['-NoLogo','-NoProfile','-NonInteractive','-Command',protect],{
  input:JSON.stringify(recovery.privateKey),
  env:{...process.env,MYR5_RECOVERY_PATH:recoveryPath}
 });
}catch(error){
 try{rmSync(recoveryPath,{force:true});}catch{}
 throw error;
}

const entry=(keyId,role,publicKey)=>({keyId,role,protocols:[1],publicKey:{kty:'OKP',crv:'Ed25519',x:publicKey.x,ext:true}});
const keys=[entry(activeId,'release',active.publicKey),entry(recoveryId,'recovery',recovery.publicKey)];
const source=`// Generated by scripts/provision-pack-catalog-keys.mjs. Private keys never belong in this repository.\nexport const PUBLIC_PACK_CATALOG_KEYS=Object.freeze(${JSON.stringify(keys,null,2)}.map(entry=>Object.freeze({...entry,protocols:Object.freeze(entry.protocols),publicKey:Object.freeze(entry.publicKey)})));\n`;
const temporary=new URL('../packs/.catalog-keys.generated.tmp',import.meta.url);
writeFileSync(temporary,source,{encoding:'utf8',flag:'wx'});
renameSync(temporary,output);

console.log(JSON.stringify({
 repository,
 active:{keyId:activeId,fingerprint:`sha256:${activeFingerprint}`,secret:activeSecret},
 recovery:{keyId:recoveryId,fingerprint:`sha256:${recoveryFingerprint}`,encryptedPath:recoveryPath},
 publicKeyring:new URL('../packs/catalog-keys.generated.mjs',import.meta.url).pathname
},null,2));
