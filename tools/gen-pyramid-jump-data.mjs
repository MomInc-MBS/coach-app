// One-off generator: compact paper shapes (silhouette + eye only) + colour table for arcade/pyramid-jump/data.mjs.
// Usage: node tools/gen-pyramid-jump-data.mjs [path/to/girlfriend-roster.js]
import {build} from 'esbuild';import {writeFileSync} from 'node:fs';import {pathToFileURL} from 'node:url';
const roster=process.argv[2]||'D:/MBS-corgi-refresh/tv/channels/girlfriend-roster.js';
const {PAPER_SHAPES}=await import(pathToFileURL(roster).href);
globalThis.window=globalThis;globalThis.localStorage={getItem:()=>null,setItem(){},removeItem(){}};
const entry="export {STYLES} from './creature/source/creator/design.ts';export * from './creature/source/creator/materials-registry.ts';";
const {outputFiles:[out]}=await build({stdin:{contents:entry,resolveDir:process.cwd(),loader:'ts'},bundle:true,write:false,format:'esm',platform:'neutral',logLevel:'silent',loader:{'.json':'json'}});
const m=await import('data:text/javascript;base64,'+Buffer.from(out.text).toString('base64'));
const colours={};
for(const c of m.COLORS||[])colours[c.id]=c.primary;
for(const p of m.PALETTES||[])colours[p.id]=p.colors[0];
const legacy=m.STYLES.map(s=>s.primary);
const rnd=d=>d.replace(/-?\d+\.\d+/g,n=>String(Math.round(+n)));
const shapes={};
for(const s of PAPER_SHAPES){const sil=s.paths.find(p=>p.region==='silhouette')||s.paths[0];shapes[s.id.replace(/^roster\//,'')]={d:rnd(sil.d),e:[s.eye.x,s.eye.y,s.eye.r].map(Math.round),v:s.viewBox};}
writeFileSync('arcade/pyramid-jump/data.mjs',`// Generated by tools/gen-pyramid-jump-data.mjs. Paper silhouettes from the Dr. Girlfriend roster + colour table.\nexport const SHAPES=${JSON.stringify(shapes)};\nexport const COLOURS=${JSON.stringify(colours)};\nexport const LEGACY=${JSON.stringify(legacy)};\n`);
console.log(Object.keys(shapes).length,Object.keys(colours).length,legacy.length);
